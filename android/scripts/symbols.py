URL = "https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded/{}/{}/24px.svg"
OUT = Path(__file__).resolve().parent.parent / "app/src/main/java/com/zeyanlin/novelreader/ui/Symbols.kt"


def path_data(name, variant):
    with urllib.request.urlopen(URL.format(name, variant), timeout=60) as response:
        svg = response.read().decode()
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1 or 'viewBox="0 -960 960 960"' not in svg:
        sys.exit(f"{name}/{variant}: expected one path in a 0 -960 960 960 box")
    return paths[0]


def main():
    lines = [
        "// Generated by scripts/symbols.py — edit the list there, not this file.",
        "package com.zeyanlin.novelreader.ui",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "/** Material Symbols Rounded, each named after the SF Symbol it replaces. */",
        "object Symbols {",
    ]
    for kotlin, name, variant, sf in SYMBOLS:
        d = path_data(name, variant)
        lines.append(f"    /** `{sf}` ← {name} ({variant}) */")
        lines.append(f'    val {kotlin}: ImageVector by lazy {{ symbol("{d}") }}')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(SYMBOLS)} symbols to {OUT}")


if __name__ == "__main__":
    main()
