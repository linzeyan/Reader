#!/usr/bin/env python3
"""Writes the OpenCC dictionaries the reader converts with, from the copy iOS ships.

iOS converts through SwiftyOpenCC, whose `.ocd2` files are compiled tries; the text
dictionaries they were compiled from sit in its OpenCC submodule. Taking them from there,
rather than from a newer OpenCC, is what makes a paragraph convert the same on both
platforms. Three of the nine are generated by OpenCC's own build, and are generated here
the same way: `TWPhrases` merges the three TW phrase lists, the `Rev` ones swap keys and
values (`data/scripts/common.py`).

Usage: opencc_dicts.py <SwiftyOpenCC checkout>
  e.g. ~/Library/Developer/Xcode/DerivedData/NovelReader-*/SourcePackages/checkouts/SwiftyOpenCC
"""
import pathlib
import shutil
import sys

ANDROID = pathlib.Path(__file__).resolve().parent.parent
OUT = ANDROID / "app/src/main/resources/opencc"
TESTS = ANDROID / "app/src/test/resources/opencc"

COPIED = ["STPhrases", "STCharacters", "TWVariants", "TWVariantsRevPhrases", "TSPhrases", "TSCharacters"]


def read(path):
    """OpenCC's `sort_items`: a later line for the same key replaces an earlier one."""
    entries = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line:
            continue
        key, value = line.split("\t")
        entries[key] = value
    return entries


def write(entries, name):
    lines = "".join(f"{key}\t{entries[key]}\n" for key in sorted(entries))
    (OUT / f"{name}.txt").write_text(lines, encoding="utf-8")


def reverse(entries):
    """OpenCC's `reverse_items`: every value becomes a key, its keys its values in input order."""
    reversed_ = {}
    for key in entries:
        for value in entries[key].split(" "):
            reversed_.setdefault(value, []).append(key)
    return {key: " ".join(values) for key, values in reversed_.items()}


def main():
    checkout = pathlib.Path(sys.argv[1]).expanduser() / "OpenCC"
    source = checkout / "data/dictionary"
    OUT.mkdir(parents=True, exist_ok=True)
    TESTS.mkdir(parents=True, exist_ok=True)
    for name in COPIED:
        write(read(source / f"{name}.txt"), name)
    tw_phrases = {}
    for part in ["TWPhrasesIT", "TWPhrasesName", "TWPhrasesOther"]:
        tw_phrases.update(read(source / f"{part}.txt"))
    write(tw_phrases, "TWPhrases")
    # Reversed from the written, sorted file, as OpenCC's build does.
    write(reverse(dict(sorted(tw_phrases.items()))), "TWPhrasesRev")
    write(reverse(read(source / "TWVariants.txt")), "TWVariantsRev")
    shutil.copyfile(checkout / "LICENSE", OUT / "LICENSE")
    for case in ["s2twp", "tw2sp"]:
        for ext in ["in", "ans"]:
            shutil.copyfile(checkout / f"test/testcases/{case}.{ext}", TESTS / f"{case}.{ext}")
    print(f"wrote {len(COPIED) + 3} dictionaries to {OUT.relative_to(ANDROID)}")


if __name__ == "__main__":
    main()
